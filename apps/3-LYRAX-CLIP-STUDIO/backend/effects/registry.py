"""Dynamic effect-plugin discovery. Adding a plugin does not require editing the renderer."""
from __future__ import annotations

import copy
import importlib
import logging
import pkgutil
import re
from pathlib import Path
from types import ModuleType
from typing import Any

logger = logging.getLogger(__name__)
_EFFECT_ID_RE = re.compile(r"^[a-z][a-z0-9_-]*$")
_PACKAGE_DIR = Path(__file__).resolve().parent


def discover_effects() -> dict[str, ModuleType]:
    """Import every valid plugin module present in ``backend/effects``.

    Discovery is intentionally directory-based rather than a hard-coded list.
    A broken optional plugin is logged and skipped, leaving other effects usable.
    """
    importlib.invalidate_caches()
    discovered: dict[str, ModuleType] = {}
    for module_info in pkgutil.iter_modules([str(_PACKAGE_DIR)]):
        if module_info.name.startswith("_") or module_info.name in {"registry", "audio", "utils"}:
            continue
        module_name = f"{__package__}.{module_info.name}"
        try:
            module = importlib.import_module(module_name)
            spec = getattr(module, "EFFECT_SPEC", None)
            if not isinstance(spec, dict):
                continue
            effect_id = str(spec.get("id", ""))
            if not _EFFECT_ID_RE.fullmatch(effect_id):
                raise ValueError(f"invalid effect id: {effect_id!r}")
            if effect_id != module_info.name:
                raise ValueError(
                    f"effect id {effect_id!r} must match module filename {module_info.name!r}"
                )
            for method_name in ("build_events", "render_ass"):
                if not callable(getattr(module, method_name, None)):
                    raise TypeError(f"plugin {effect_id!r} is missing {method_name}()")
            if effect_id in discovered:
                raise ValueError(f"duplicate effect id: {effect_id!r}")
            discovered[effect_id] = module
        except Exception:
            logger.exception("Skipping invalid LyraX effect plugin %s", module_name)
    return discovered


def get_effect_plugins() -> dict[str, ModuleType]:
    """Return the discovered plugin map (a fresh scan also notices new files)."""
    return discover_effects()


def get_effect_plugin(effect_id: str) -> ModuleType | None:
    return get_effect_plugins().get(str(effect_id or ""))


def get_effect_specs() -> list[dict[str, Any]]:
    """Return JSON-safe public manifests for the browser effect-layer manager."""
    specs: list[dict[str, Any]] = []
    for effect_id, module in get_effect_plugins().items():
        spec = copy.deepcopy(module.EFFECT_SPEC)
        spec["preview_module"] = f"/static/js/effects/{effect_id}.js"
        specs.append(spec)
    return sorted(specs, key=lambda spec: (int(spec.get("order", 100)), spec["id"]))


def normalize_effect_layer(
    layer: dict[str, Any],
    index: int = 0,
    plugins: dict[str, ModuleType] | None = None,
) -> dict[str, Any]:
    """Normalize a project effect layer while preserving plugin-specific settings."""
    if not isinstance(layer, dict):
        return {}
    effect_type = str(layer.get("type") or layer.get("effect_type") or "").strip()
    plugin = (plugins if plugins is not None else get_effect_plugins()).get(effect_type)
    spec = getattr(plugin, "EFFECT_SPEC", {}) if plugin else {}
    defaults = spec.get("defaults", {}) if isinstance(spec, dict) else {}
    settings = layer.get("settings", layer.get("config", {}))
    if not isinstance(settings, dict):
        settings = {}
    events = layer.get("events", [])
    if not isinstance(events, list):
        events = []
    layer_id = str(layer.get("id") or f"effect-{effect_type or 'unknown'}-{index + 1}")
    # IDs are later used in DOM data attributes. Normalize imported IDs to a safe,
    # stable token without discarding IDs generated by older project files.
    safe_id = re.sub(r"[^A-Za-z0-9_-]", "-", layer_id).strip("-") or f"effect-{index + 1}"
    try:
        order = int(layer.get("order", index))
    except (TypeError, ValueError):
        order = index
    try:
        start_time = max(0.0, float(layer.get("start_time", 0.0) or 0.0))
    except (TypeError, ValueError):
        start_time = 0.0
    end_time = layer.get("end_time")
    try:
        end_time = None if end_time in (None, "") else max(start_time, float(end_time))
    except (TypeError, ValueError):
        end_time = None
    merged_settings = copy.deepcopy(defaults) if isinstance(defaults, dict) else {}
    merged_settings.update(copy.deepcopy(settings))
    enabled_value = layer.get("enabled", True)
    if isinstance(enabled_value, str):
        enabled_value = enabled_value.strip().lower() not in {"", "0", "false", "no", "off"}
    name = str(layer.get("name") or spec.get("name") or effect_type or "Effect")
    return {
        "id": safe_id,
        "type": effect_type,
        "name": name,
        "enabled": bool(enabled_value),
        "order": order,
        "start_time": start_time,
        "end_time": end_time,
        "settings": merged_settings,
        "events": copy.deepcopy(events),
    }


def render_effect_layers(renderer, layers, context) -> list[str]:
    """Render every enabled effect layer through its plugin; unknown types are skipped."""
    if not isinstance(layers, list):
        return []
    plugins = get_effect_plugins()
    normalized = [normalize_effect_layer(layer, i, plugins=plugins) for i, layer in enumerate(layers)]
    normalized = [layer for layer in normalized if layer and layer.get("type")]
    normalized.sort(key=lambda layer: (layer.get("order", 0), layer.get("id", "")))
    output: list[str] = []
    for index, layer in enumerate(normalized):
        if not layer.get("enabled", True):
            continue
        plugin = plugins.get(layer["type"])
        if plugin is None:
            logger.warning("No renderer registered for effect layer type %s", layer["type"])
            continue
        try:
            events = plugin.build_events(layer, context)
            if not isinstance(events, list) or not events:
                continue
            # Lyrics occupy ASS layers 0-1; the watermark is placed after all effects.
            ass_layer = 2 + index
            lines = plugin.render_ass(
                renderer,
                layer,
                events,
                int(context["width"]),
                int(context["height"]),
                ass_layer=ass_layer,
            )
            if lines:
                output.extend(str(line) for line in lines)
        except Exception:
            # A broken/malformed layer should not prevent the base video and other
            # valid effect layers from rendering.
            logger.exception("Skipping failed effect plugin %s for layer %s", layer["type"], layer["id"])
    return output
